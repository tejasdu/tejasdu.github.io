export function renderTechIcon(techName) {
  if (!techName) return null

  // Direct match
  if (TechIcons[techName]) {
    const Icon = TechIcons[techName]
    return <span className="inline-flex items-center justify-center shrink-0"><Icon /></span>
  }

  // Normalized key match (strips punctuation, whitespace, dots, slashes)
  const clean = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '')
  const targetClean = clean(techName)

  for (const [key, Icon] of Object.entries(TechIcons)) {
    if (clean(key) === targetClean) {
      return <span className="inline-flex items-center justify-center shrink-0"><Icon /></span>
    }
  }

  // Fallback minimalist vector brackets icon
  return (
    <span className="inline-flex items-center justify-center shrink-0">
      <svg viewBox="0 0 24 24" className="size-3.5 stroke-zinc-400 stroke-2 fill-none" xmlns="http://www.w3.org/2000/svg">
        <polyline points="16 18 22 12 16 6"/>
        <polyline points="8 6 2 12 8 18"/>
      </svg>
    </span>
  )
}
